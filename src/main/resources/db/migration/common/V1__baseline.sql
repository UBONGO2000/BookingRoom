-- P2-20 : baseline du schema existant (avant Flyway, cree par Hibernate).
-- Les evolutions suivantes sont dans V2 (statut de reservation) et V3 (index).

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    firstname VARCHAR(255) NOT NULL,
    lastname VARCHAR(255) NOT NULL,
    username VARCHAR(255) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    email VARCHAR(255) NOT NULL,
    password VARCHAR(100) NOT NULL,
    role VARCHAR(255) NOT NULL,
    CONSTRAINT uk_users_username UNIQUE (username),
    CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE TABLE room (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    description VARCHAR(1000),
    capacity INTEGER NOT NULL,
    location VARCHAR(255) NOT NULL,
    projector BOOLEAN NOT NULL,
    whiteboard BOOLEAN NOT NULL,
    videoconferencing BOOLEAN NOT NULL,
    available BOOLEAN NOT NULL,
    available_from TIMESTAMP(6),
    available_until TIMESTAMP(6),
    CONSTRAINT uk_room_name UNIQUE (name)
);

CREATE TABLE booking (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    start_time TIMESTAMP(6) NOT NULL,
    end_time TIMESTAMP(6) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'CONFIRMED',
    cancelled_at TIMESTAMP(6),
    user_id BIGINT NOT NULL,
    room_id BIGINT NOT NULL,
    CONSTRAINT fk_booking_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_booking_room FOREIGN KEY (room_id) REFERENCES room (id)
);
